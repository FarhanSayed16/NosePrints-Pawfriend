"""
Offline eval: two-stage dog→nose detect + look-gate on ml/data/phone_eval/*.

Writes FAILURE_MAP.md with per-image stage tags.

Usage (from repo, with backend PYTHONPATH):
  set PYTHONPATH=D:\\NosePrints-Pawfriend\\backend
  backend\\venv\\Scripts\\python.exe scripts\\eval_phone_detect.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.config import settings
from app.services.dog_detector import dog_detector
from app.services.look_gate import assess_look_photo
from app.services.nose_detector import nose_detector
from app.services.nose_heuristics import suggest_nose_bbox_norm


def _tag(det, hint) -> str:
    accept = float(settings.DETECTOR_MIN_ACCEPT_CONF)
    nose_ok = det.bbox is not None and float(det.confidence) >= accept
    if nose_ok:
        return "success_or_strong_nose"
    if det.dog_bbox is None and det.bbox is None:
        # Could be junk negative or Stage-1 miss on a dog scene
        if hint is not None:
            return "stage2_miss_assist_hint"
        return "stage1_miss_or_no_dog"
    if det.dog_bbox is not None and (det.bbox is None or float(det.confidence) < accept):
        return "stage2_miss_loose_assist" if hint is not None else "stage2_miss_no_assist"
    return "weak_nose_below_accept"


def main() -> int:
    folder = ROOT / "ml" / "data" / "phone_eval"
    folder.mkdir(parents=True, exist_ok=True)
    images = sorted(
        p
        for p in folder.iterdir()
        if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}
    )
    if not images:
        print(f"No images in {folder}")
        print("Add failed phone JPEGs there, then re-run.")
        return 1

    nose_detector.load()
    dog_detector.load()
    print(f"nose_loaded={nose_detector.is_loaded} dog_loaded={dog_detector.is_loaded}")
    print(f"Evaluating {len(images)} images\n")

    rows: list[dict] = []
    for path in images:
        data = path.read_bytes()
        det = nose_detector.detect(data)
        hint = suggest_nose_bbox_norm(det.original, dog_bbox=det.dog_bbox)
        look = assess_look_photo(data)
        tag = _tag(det, hint)
        row = {
            "name": path.name,
            "nose_conf": float(det.confidence or 0),
            "nose_box": det.bbox,
            "dog_conf": float(det.dog_confidence or 0),
            "dog_box": det.dog_bbox,
            "hint": hint is not None,
            "look_soft": look.soft_warn,
            "look_issues": look.issues[:1],
            "tag": tag,
        }
        rows.append(row)
        print(
            f"{path.name}: tag={tag} nose_conf={row['nose_conf']:.3f} nose_box={det.bbox} "
            f"dog_conf={row['dog_conf']:.3f} dog_box={det.dog_bbox} "
            f"hint={hint is not None} look_soft={look.soft_warn} "
            f"look_issues={look.issues[:1]}"
        )

    # Dominant fail stage among non-success tags
    from collections import Counter

    fail_tags = [r["tag"] for r in rows if not r["tag"].startswith("success")]
    counts = Counter(fail_tags)
    dominant = counts.most_common(1)[0][0] if counts else "none"

    map_path = folder / "FAILURE_MAP.md"
    lines = [
        "# Phone eval failure map",
        "",
        f"Generated by `scripts/eval_phone_detect.py`. Images: **{len(rows)}**.",
        "",
        f"**Dominant non-success tag:** `{dominant}`",
        "",
        "| File | Tag | nose_conf | dog_conf | hint |",
        "|------|-----|-----------|----------|------|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['name']}` | `{r['tag']}` | {r['nose_conf']:.3f} | {r['dog_conf']:.3f} | {r['hint']} |"
        )
    lines.extend(
        [
            "",
            "## Tag legend",
            "",
            "- `success_or_strong_nose` — Stage-2 above accept conf",
            "- `stage2_miss_loose_assist` — dog found, nose weak/miss, heuristic hint present",
            "- `stage2_miss_no_assist` — dog found, no nose, no hint",
            "- `stage1_miss_or_no_dog` — no dog box (junk negative or Stage-1 miss)",
            "- `stage2_miss_assist_hint` — no dog box but assist hint still produced",
            "",
            "## Owner note",
            "",
            "Replace seed/junk images with **real failed field dog JPEGs** when available.",
            "Ignore keyboard/dark post-fail camera screenshots — they are not scan inputs.",
            "",
        ]
    )
    map_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {map_path}")
    print(f"Dominant non-success tag: {dominant}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
